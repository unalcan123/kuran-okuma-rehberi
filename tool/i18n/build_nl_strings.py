#!/usr/bin/env python3
"""Hollandaca çevirileri tek Dart dosyasına yazar: lib/l10n/strings/nl_strings.g.dart.

Kaynak (elle düzenlenen):
  tool/i18n/ui_nl.json       arayüz + oyun yönergeleri: Türkçe metin → Hollandaca
  tool/i18n/content_nl.json  ders metinleri: Türkçe metin → Hollandaca

Uygulama bu tabloyu `L10n.table` satırlarına 6. sütun olarak ekler (diğer dillerin
satırları değişmez). Bir metin iki dosyada da varsa iki karşılık aynı olmalı.

Kullanım (depo kökünden):  python tool/i18n/build_nl_strings.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCES = [ROOT / "tool/i18n/ui_nl.json", ROOT / "tool/i18n/content_nl.json"]
TARGET = ROOT / "lib/l10n/strings/nl_strings.g.dart"


def dart_string(text: str) -> str:
    return json.dumps(text, ensure_ascii=False).replace("$", "\\$")


def main() -> int:
    merged: dict[str, str] = {}
    for source in SOURCES:
        for key, value in json.loads(source.read_text(encoding="utf-8")).items():
            if not value.strip():
                print(f"{source.name}: boş çeviri: {key!r}", file=sys.stderr)
                return 1
            if key in merged and merged[key] != value:
                print(f"İki farklı karşılık: {key!r}: {merged[key]!r} / {value!r}", file=sys.stderr)
                return 1
            merged[key] = value
    lines = [
        "// Generated by tool/i18n/build_nl_strings.py from tool/i18n/ui_nl.json",
        "// and tool/i18n/content_nl.json. Do not edit by hand.",
        "// Turkish source text → Dutch (the 6th column of L10n.table).",
        "const Map<String, String> kNlStrings = {",
    ]
    for key, value in merged.items():
        one_line = f"  {dart_string(key)}: {dart_string(value)},"
        lines.append(
            one_line if len(one_line) <= 80 else f"  {dart_string(key)}:\n      {dart_string(value)},"
        )
    lines.append("};")
    TARGET.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{TARGET.relative_to(ROOT)}: {len(merged)} metin")
    return 0


if __name__ == "__main__":
    sys.exit(main())
