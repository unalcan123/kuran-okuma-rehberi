#!/usr/bin/env python3
"""Almanca ve Boşnakça arayüz çevirilerini Dart dosyasına yazar.

Kaynak (elle düzenlenen): tool/i18n/ui_de.json, tool/i18n/ui_bs.json
(Türkçe metin → çeviri). Çıktı: lib/l10n/strings/debs_strings.g.dart
(kDeStrings, kBsStrings). L10n.table bir satırın de/bs sütunu boşsa bunları
kullanır; tablolarda zaten olan çeviriye dokunulmaz.

Kullanım (depo kökünden): python tool/i18n/build_debs_strings.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TARGET = ROOT / "lib/l10n/strings/debs_strings.g.dart"


def dart(text: str) -> str:
    return json.dumps(text, ensure_ascii=False).replace("$", "\\$")


def main() -> int:
    out = [
        "// Generated by tool/i18n/build_debs_strings.py from tool/i18n/ui_de.json",
        "// and tool/i18n/ui_bs.json. Do not edit by hand.",
    ]
    for lang, name in (("de", "kDeStrings"), ("bs", "kBsStrings")):
        data = json.loads((ROOT / f"tool/i18n/ui_{lang}.json").read_text(encoding="utf-8"))
        empty = [k for k, v in data.items() if not v.strip()]
        if empty:
            print(f"ui_{lang}.json: boş çeviri: {empty[:3]}", file=sys.stderr)
            return 1
        out.append(f"const Map<String, String> {name} = {{")
        for key, value in data.items():
            one = f"  {dart(key)}: {dart(value)},"
            out.append(one if len(one) <= 80 else f"  {dart(key)}:\n      {dart(value)},")
        out.append("};")
        print(f"{lang}: {len(data)} metin")
    TARGET.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
